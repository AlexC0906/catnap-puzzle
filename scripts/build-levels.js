#!/usr/bin/env node
// Builds src/levels.js: the hand-tuned Journey progression.
// Each level is generated deterministically, rated by the logic solver and
// stored compactly (one character per cell = cushion id).
const fs = require('fs');
const path = require('path');
const E = require('../src/engine.js');
const L = require('../src/logic.js');

// [size, tier] for each level. Tiers: 0 easy, 1 medium, 2 hard, 3 expert.
const PLAN = [
  [5, 0], [5, 0], [5, 0], [5, 1], [5, 0], [5, 1], [6, 0], [6, 0], [6, 1], [6, 1],
  [6, 0], [6, 1], [7, 0], [7, 1], [6, 2], [7, 1], [7, 0], [7, 1], [7, 2], [7, 1],
  [8, 0], [7, 1], [8, 1], [7, 2], [8, 1], [8, 1], [8, 2], [7, 3], [8, 1], [8, 2],
  [9, 1], [8, 2], [9, 1], [8, 2], [9, 2], [8, 3], [9, 1], [9, 2], [9, 2], [8, 3],
  [9, 2], [10, 1], [9, 2], [9, 3], [10, 2], [9, 2], [10, 1], [10, 2], [9, 3], [10, 2],
  [10, 2], [9, 3], [10, 2], [10, 3], [10, 2], [9, 3], [10, 3], [10, 2], [10, 3], [10, 3]
];

const levels = PLAN.map(([n, tier], i) => {
  const p = L.generateRated(E, n, tier, 1000 + i * 7919, 3000);
  if (!p || p.tier !== tier) throw new Error(`level ${i + 1}: could not reach tier ${tier}`);
  return { n, tier, steps: p.rating.steps, r: p.regions.join('') };
});

const out = `// Generated by scripts/build-levels.js — do not edit by hand.
(function (root) {
  const LEVELS = ${JSON.stringify(levels, null, 0).replace(/\},\{/g, '},\n    {')};
  if (typeof module !== 'undefined' && module.exports) module.exports = LEVELS;
  else root.CatnapLevels = LEVELS;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'levels.js'), out);
console.log(`wrote ${levels.length} levels`);
